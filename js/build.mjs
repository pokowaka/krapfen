// Bundles js/src/krapfen.mjs + the vendored Strudel packages into one
// classic script that the native host evaluates in QuickJS.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const strudel = path.join(here, '../third_party/strudel/packages');
const outfile = path.join(here, '../krapfen/src/main/assets/krapfen/strudel.js');

const result = await build({
  entryPoints: [path.join(here, 'src/krapfen.mjs')],
  outfile,
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2023',
  minify: false,
  legalComments: 'none',
  metafile: true,
  alias: {
    '@strudel/core': path.join(strudel, 'core'),
    '@strudel/mini': path.join(strudel, 'mini'),
    '@strudel/transpiler': path.join(strudel, 'transpiler'),
    '@strudel/tonal': path.join(strudel, 'tonal'),
  },
  // The vendored packages live outside js/, so point resolution at our
  // node_modules for their third-party dependencies.
  nodePaths: [path.join(here, 'node_modules')],
  // escodegen optionally requires source-map; not needed.
  external: ['source-map'],
  // core/neocyclist.mjs uses import.meta.url for a SharedWorker clock, which
  // Krapfen never starts (it uses Cyclist).
  logOverride: { 'empty-import-meta': 'silent' },
  // Strudel's errorLogger checks process.env.NODE_ENV, which strudel.cc's
  // build (vite) replaces; there is no `process` in QuickJS.
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: {
    js: [
      '// Krapfen Strudel bundle. Generated by js/build.mjs; do not edit.',
      '// Contains Strudel (https://codeberg.org/uzu/strudel), AGPL-3.0-or-later,',
      '// and its dependencies; see third_party/ and js/package.json.',
    ].join('\n'),
  },
});

const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`wrote ${path.relative(process.cwd(), outfile)} (${(bytes / 1024).toFixed(0)} KB)`);
